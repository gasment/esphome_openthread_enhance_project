"""Pack BR/commissioner frontend into deterministic gzip C assets."""
import gzip
import re
from pathlib import Path
ROOT=Path(__file__).resolve().parent
WEB=ROOT/'thread_br_web'
ASSETS=(('index.html','text/html; charset=utf-8'),('commissioner.html','text/html; charset=utf-8'),
        ('static/commissioner.js','application/javascript; charset=utf-8'),('topology.html','text/html; charset=utf-8'),
        ('tools.html','text/html; charset=utf-8'),('about.html','text/html; charset=utf-8'),
        ('static/api.js','application/javascript; charset=utf-8'),('static/style.css','text/css; charset=utf-8'),('favicon.ico','image/x-icon'))
COMMISSIONER_ASSETS={'commissioner.html','static/commissioner.js'}
COMMISSIONER_GUARD='CONFIG_THREAD_BR_COMMISSIONER_WEB'

def without_commissioner_navigation(raw):
    text,count=re.subn(r'// THREAD_COMMISSIONER_NAV_BEGIN\r?\n.*?// THREAD_COMMISSIONER_NAV_END\r?\n','',raw.decode(),flags=re.S)
    if count != 1: raise ValueError('Expected commissioner navigation marker')
    return text.encode()

def build_header():
    lines=['// Generated by components/esp32/thread_br/build_web_assets.py; do not edit directly.',
           '// Adapted Espressif assets, Apache-2.0. Sources: frontend/.','#pragma once','#include "sdkconfig.h"',
           '#include <stddef.h>','typedef struct { const char *path; const char *type; const unsigned char *data; size_t size; } br_asset_t;']
    def append(index,raw):
        data=bytearray(gzip.compress(raw,compresslevel=9,mtime=0)); data[9]=255
        lines.append(f'static const unsigned char br_asset_{index}[] = {{')
        lines.extend(','.join(f'0x{b:02x}' for b in data[i:i+24])+',' for i in range(0,len(data),24)); lines.append('};')
        return len(data)
    total=0
    for index,(name,_) in enumerate(ASSETS):
        raw=(WEB/'frontend'/name).read_bytes()
        if name != 'favicon.ico': raw.decode()
        guard=COMMISSIONER_GUARD if name in COMMISSIONER_ASSETS else None
        if guard: lines.append(f'#ifdef {guard}')
        if name=='static/api.js':
            lines.append(f'#ifdef {COMMISSIONER_GUARD}'); total+=append(index,raw)
            lines.append('#else'); append(index,without_commissioner_navigation(raw)); lines.append('#endif')
        else: total+=append(index,raw)
        if guard: lines.append('#endif')
    lines.append('static const br_asset_t br_assets[] = {')
    for index,(name,mime) in enumerate(ASSETS):
        if name in COMMISSIONER_ASSETS: lines.append(f'#ifdef {COMMISSIONER_GUARD}')
        lines.append(f'{{"/{name}", "{mime}", br_asset_{index}, sizeof(br_asset_{index})}},')
        if name in COMMISSIONER_ASSETS: lines.append('#endif')
    lines.append('};')
    return '\n'.join(lines)+'\n',total

def main():
    content,total=build_header(); target=WEB/'web_assets.h'
    if not target.exists() or target.read_text(encoding='utf-8') != content:
        target.write_text(content,encoding='utf-8',newline='\n')
    print(f'Packed {len(ASSETS)} Web assets ({total} gzip bytes): {target.relative_to(ROOT)}')

if __name__=='__main__': main()
