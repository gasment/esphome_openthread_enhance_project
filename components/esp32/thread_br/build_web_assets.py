"""Pack the component's editable Web frontend into deterministic gzip C assets."""

import gzip
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
WEB = ROOT / "thread_br_web"
ASSETS = (
    ("index.html", "text/html; charset=utf-8"),
    ("thread_gateway.html", "text/html; charset=utf-8"),
    ("commissioner.html", "text/html; charset=utf-8"),
    ("static/commissioner.js", "application/javascript; charset=utf-8"),
    ("static/thread_gateway.js", "application/javascript; charset=utf-8"),
    ("topology.html", "text/html; charset=utf-8"),
    ("tools.html", "text/html; charset=utf-8"),
    ("about.html", "text/html; charset=utf-8"),
    ("static/api.js", "application/javascript; charset=utf-8"),
    ("static/style.css", "text/css; charset=utf-8"),
    ("favicon.ico", "image/x-icon"),
)


GATEWAY_ASSETS = {"thread_gateway.html", "static/thread_gateway.js"}
GATEWAY_GUARD = "CONFIG_THREAD_BR_GATEWAY_WEB"
COMMISSIONER_ASSETS = {"commissioner.html", "static/commissioner.js"}
COMMISSIONER_GUARD = "CONFIG_THREAD_BR_COMMISSIONER_WEB"


def without_gateway_navigation(raw):
    text = raw.decode("utf-8")
    pattern = r"// THREAD_GATEWAY_NAV_BEGIN\r?\n.*?// THREAD_GATEWAY_NAV_END\r?\n"
    text, count = re.subn(pattern, "", text, flags=re.S)
    if count != 2:
        raise ValueError("Expected gateway entry and discovery markers in shared navigation")
    return text.encode("utf-8")


def without_commissioner_navigation(raw):
    text, count = re.subn(r"// THREAD_COMMISSIONER_NAV_BEGIN\r?\n.*?// THREAD_COMMISSIONER_NAV_END\r?\n",
                          "", raw.decode("utf-8"), flags=re.S)
    if count != 1:
        raise ValueError("Expected commissioner navigation markers")
    return text.encode("utf-8")


def build_header():
    lines = [
        "// Generated by components/esp32/thread_br/build_web_assets.py; do not edit directly.",
        "// Adapted Espressif assets, Apache-2.0. Sources: frontend/.",
        "#pragma once",
        '#include "sdkconfig.h"',
        "#include <stddef.h>",
        "typedef struct { const char *path; const char *type; const unsigned char *data; size_t size; } br_asset_t;",
    ]
    def append_array(index, raw):
        data = bytearray(gzip.compress(raw, compresslevel=9, mtime=0))
        data[9] = 255  # Normalize gzip OS byte across Windows and WSL builds.
        lines.append(f"static const unsigned char br_asset_{index}[] = {{")
        lines.extend(",".join(f"0x{byte:02x}" for byte in data[offset:offset + 24]) + ","
                     for offset in range(0, len(data), 24))
        lines.append("};")
        return len(data)

    total = 0
    for index, (name, _) in enumerate(ASSETS):
        raw = (WEB / "frontend" / name).read_bytes()
        if not name.endswith(".ico"):
            raw.decode("utf-8")
        if name == "static/api.js":
            # Four independent compile-time variants. Disabled features leave
            # neither navigation entries nor feature-discovery requests behind.
            for gateway in (True, False):
                lines.append(f"#ifdef {GATEWAY_GUARD}" if gateway else "#else")
                for commission in (True, False):
                    lines.append(f"#ifdef {COMMISSIONER_GUARD}" if commission else "#else")
                    variant = raw if gateway else without_gateway_navigation(raw)
                    variant = variant if commission else without_commissioner_navigation(variant)
                    size = append_array(index, variant)
                    if gateway and commission: total += size
                lines.append("#endif")
            lines.append("#endif")
        else:
            guard = GATEWAY_GUARD if name in GATEWAY_ASSETS else COMMISSIONER_GUARD if name in COMMISSIONER_ASSETS else None
            if guard: lines.append(f"#ifdef {guard}")
            total += append_array(index, raw)
            if guard: lines.append("#endif")
    lines.append("static const br_asset_t br_assets[] = {")
    for index, (name, mime) in enumerate(ASSETS):
        guard = GATEWAY_GUARD if name in GATEWAY_ASSETS else COMMISSIONER_GUARD if name in COMMISSIONER_ASSETS else None
        if guard: lines.append(f"#ifdef {guard}")
        lines.append(f'{{"/{name}", "{mime}", br_asset_{index}, sizeof(br_asset_{index})}},')
        if guard: lines.append("#endif")
    lines.append("};")
    return "\n".join(lines) + "\n", total


def main():
    content, total = build_header()
    target = WEB / "web_assets.h"
    if not target.exists() or target.read_text(encoding="utf-8") != content:
        target.write_text(content, encoding="utf-8", newline="\n")
    print(f"Packed {len(ASSETS)} Web assets ({total} gzip bytes with gateway enabled): {target.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
